package crm.seed

import org.slf4j.LoggerFactory
import org.springframework.boot.ApplicationArguments
import org.springframework.boot.ApplicationRunner
import org.springframework.context.annotation.Profile
import org.springframework.jdbc.core.simple.JdbcClient
import org.springframework.security.crypto.password.PasswordEncoder
import org.springframework.stereotype.Component
import java.sql.Types

/**
 * CRM_MODE=seed (Spring profile `seed`, migrator login): computes the password hash once with the application's
 * PasswordEncoder (so k6 logs in through the real endpoint) and calls `EXEC seed.run`, then `EXEC seed.desk_run`
 * (the service desk, idempotent). All data is generated by the procedures. CRM_SEED_DESK_ONLY=true runs only the
 * desk part. Invalid settings stop the process with a non-zero exit code.
 */
@Component
@Profile("seed")
class SeedRunner(
    private val properties: SeedProperties,
    private val jdbc: JdbcClient,
    private val passwordEncoder: PasswordEncoder,
) : ApplicationRunner {
    private val log = LoggerFactory.getLogger(javaClass)

    override fun run(args: ApplicationArguments) {
        val password = properties.password?.takeIf { it.length >= 8 }
            ?: throw IllegalStateException("CRM_SEED_PASSWORD must be set (at least 8 characters).")
        val p = properties
        val hash = passwordEncoder.encode(password)
        if (!p.deskOnly) seedCrm(p, hash!!)
        jdbc.sql("EXEC seed.desk_run @password_hash = :hash, @tickets = :tickets, @random_seed = :randomSeed")
            .param("hash", hash, Types.VARCHAR)
            .param("tickets", p.deskTickets, Types.INTEGER)
            .param("randomSeed", p.randomSeed, Types.INTEGER)
            .update()
        log.info("Desk seed finished: up to {} tickets", p.deskTickets)
    }

    private fun seedCrm(p: SeedProperties, hash: String) {
        log.info(
            "Seeding: {} clients, {} projects, {} comments, users {}/{}/{} (admin/manager/sales), team size {}",
            p.clients, p.projects, p.comments, p.admins, p.managers, p.sales, p.teamSize,
        )

        val result = jdbc.sql(
            "EXEC seed.run @clients = :clients, @admins = :admins, @managers = :managers, @sales = :sales, " +
                "@password_hash = :hash, @team_size = :teamSize, @projects = :projects, @comments = :comments, " +
                "@random_seed = :randomSeed, @batch_size = :batchSize",
        )
            .param("clients", p.clients, Types.INTEGER)
            .param("admins", p.admins, Types.INTEGER)
            .param("managers", p.managers, Types.INTEGER)
            .param("sales", p.sales, Types.INTEGER)
            .param("hash", hash, Types.VARCHAR)
            .param("teamSize", p.teamSize, Types.INTEGER)
            .param("projects", p.projects, Types.INTEGER)
            .param("comments", p.comments, Types.INTEGER)
            .param("randomSeed", p.randomSeed, Types.INTEGER)
            .param("batchSize", p.batchSize, Types.INTEGER)
            .query { rs, _ ->
                "users=${rs.getInt("users_created")} teams=${rs.getInt("teams_created")} " +
                    "clients=${rs.getInt("clients_created")} projects=${rs.getInt("projects_created")} " +
                    "comments=${rs.getInt("comments_created")} seconds=${rs.getInt("seconds")}"
            }
            .single()

        log.info("Seed finished: {}", result)
    }
}
